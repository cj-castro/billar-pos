#!/usr/bin/env python3
"""Generate backend/migrations/sql/001_baseline_squash.sql from a pg_dump schema.

WHY A SNAPSHOT ALONE IS NOT ENOUGH
----------------------------------
The entrypoint runs `flask init-db` BEFORE `flask apply-migrations`, so most
tables already exist when the baseline is applied. A plain pg_dump snapshot
uses CREATE TABLE, which would either fail or (with IF NOT EXISTS) silently
skip the table and leave behind every column that migrations 027-039 added.

So the baseline emits two passes:
  1. CREATE TABLE IF NOT EXISTS   -- builds anything missing (fresh database)
  2. ADD COLUMN IF NOT EXISTS     -- backfills columns onto tables init-db
                                     already created (upgrade path)
Together they converge to the same schema from either starting point.

Usage:
  python scripts/gen_baseline_squash.py <schema_dump.sql> <columns.tsv> <out.sql>
"""
from __future__ import annotations

import re
import sys

HEADER = """-- ============================================================================
-- 001_baseline_squash.sql -- squashed schema baseline
--
-- GENERATED by scripts/gen_baseline_squash.py from the production schema.
-- Do not hand-edit; regenerate instead.
--
-- Replaces migrations 027..039, which are retained on disk for history but are
-- no longer listed in manifest.txt.
--
-- Every statement is idempotent, because this file must be safe to apply:
--   * to a fresh database (nothing exists yet), and
--   * immediately after `flask init-db` (34 of 52 tables already exist), and
--   * to an already-provisioned production database (everything exists).
--
-- Atomic: the whole file is one transaction. migrations_runner.py connects with
-- autocommit=True, so atomicity is a property of THIS file, not the runner.
-- Contains no CREATE INDEX CONCURRENTLY, which cannot run inside a transaction.
-- ============================================================================

BEGIN;

-- --------------------------------------------------------------------------
-- Check 6a: re-apply guard.
--
-- version_of('001_baseline_squash') is '001'. Databases provisioned before the
-- squash recorded 027..039 but never '001', and the runner skips only on an
-- exact version match -- so without this seed the baseline would read as
-- PENDING and re-run a full schema build against live data on every upgraded
-- install. Seeding '001' when historical versions >= '027' are present makes
-- the runner skip it there, while a fresh database still applies it normally.
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS schema_migrations (
    version    varchar(20)  PRIMARY KEY,
    name       varchar(200) NOT NULL,
    applied_at timestamptz  NOT NULL DEFAULT now(),
    applied_by varchar(100) NOT NULL DEFAULT current_user,
    notes      text
);

DO $baseline_guard$
BEGIN
    IF EXISTS (SELECT 1 FROM schema_migrations WHERE version >= '027') THEN
        INSERT INTO schema_migrations (version, name, notes)
        SELECT '001', '001_baseline_squash',
               'seeded by the baseline re-apply guard; schema predates the squash'
        WHERE NOT EXISTS (SELECT 1 FROM schema_migrations WHERE version = '001');
        RAISE NOTICE '001_baseline_squash: existing install detected '
                     '(027+ recorded); seeded version 001, schema left as-is.';
    END IF;
END
$baseline_guard$;

SET LOCAL statement_timeout = 0;
SET LOCAL lock_timeout = '30s';

-- pg_dump emits functions alphabetically, not in dependency order, so a
-- SQL-language function can forward-reference one defined further down and
-- fail validation at CREATE time. Deferring body checks lets the whole set be
-- created in any order; the bodies are still checked at execution time.
SET LOCAL check_function_bodies = false;
"""

FOOTER = """
-- --------------------------------------------------------------------------
-- Register this baseline. The WHERE NOT EXISTS keeps the row seeded by the
-- guard above intact, and avoids depending on a particular unique constraint.
-- --------------------------------------------------------------------------
INSERT INTO schema_migrations (version, name, notes)
SELECT '001', '001_baseline_squash', 'squashed baseline replacing 027..039'
WHERE NOT EXISTS (SELECT 1 FROM schema_migrations WHERE version = '001');

DO $done$ BEGIN RAISE NOTICE '001_baseline_squash: OK'; END $done$;

COMMIT;
"""

# Objects that must never be carried into the baseline.
SKIP_TABLES = {
    'alembic_version',                      # dead legacy bookkeeping
    'schema_migrations',                    # created by the guard above
    'menu_item_ingredients_archive_029b',   # one-shot archive from migration 029b
}


def split_statements(sql: str) -> list[str]:
    """Split a pg_dump into statements, respecting $$-quoted function bodies."""
    out, buf, dollar_tag = [], [], None
    for line in sql.splitlines():
        stripped = line.strip()
        if not dollar_tag:
            if stripped.startswith('--') or not stripped:
                continue
        buf.append(line)
        for tag in re.findall(r'\$[A-Za-z_0-9]*\$', line):
            if dollar_tag is None:
                dollar_tag = tag
            elif tag == dollar_tag:
                dollar_tag = None
        if dollar_tag is None and stripped.endswith(';'):
            out.append('\n'.join(buf).strip())
            buf = []
    if buf:
        out.append('\n'.join(buf).strip())
    return out


def table_of(stmt: str) -> str | None:
    m = re.search(r'(?:CREATE TABLE|ALTER TABLE(?: ONLY)?)\s+'
                  r'(?:public\.)?"?([A-Za-z_0-9]+)"?', stmt)
    return m.group(1) if m else None


def emit(statements: list[str], columns: list[tuple]) -> str:
    tables, seqs, funcs, views, indexes, constraints, triggers = (
        [], [], [], [], [], [], [])

    for st in statements:
        head = st.lstrip()
        upper = head.upper()

        if upper.startswith('SET ') or upper.startswith('SELECT PG_CATALOG'):
            continue
        if upper.startswith('COMMENT ON'):
            continue

        if upper.startswith('CREATE TABLE'):
            name = table_of(st)
            if name in SKIP_TABLES:
                continue
            tables.append(st.replace('CREATE TABLE ', 'CREATE TABLE IF NOT EXISTS ', 1))

        elif upper.startswith('CREATE SEQUENCE'):
            seqs.append(st.replace('CREATE SEQUENCE ', 'CREATE SEQUENCE IF NOT EXISTS ', 1))

        elif upper.startswith('CREATE FUNCTION'):
            funcs.append(st.replace('CREATE FUNCTION ', 'CREATE OR REPLACE FUNCTION ', 1))

        elif upper.startswith('CREATE VIEW'):
            views.append(st.replace('CREATE VIEW ', 'CREATE OR REPLACE VIEW ', 1))

        elif upper.startswith('CREATE INDEX') or upper.startswith('CREATE UNIQUE INDEX'):
            # CONCURRENTLY cannot run inside a transaction block.
            st = st.replace(' CONCURRENTLY', '')
            st = re.sub(r'CREATE (UNIQUE )?INDEX (?!IF NOT EXISTS)',
                        r'CREATE \1INDEX IF NOT EXISTS ', st, count=1)
            indexes.append(st)

        elif upper.startswith('CREATE TRIGGER') or upper.startswith('CREATE CONSTRAINT TRIGGER'):
            m = re.match(r'CREATE (?:CONSTRAINT )?TRIGGER\s+"?([A-Za-z_0-9]+)"?', head)
            tbl = re.search(r'\sON\s+(?:public\.)?"?([A-Za-z_0-9]+)"?', st)
            if m and tbl:
                triggers.append(
                    f'DROP TRIGGER IF EXISTS {m.group(1)} ON public.{tbl.group(1)};\n{st}')

        elif upper.startswith('ALTER TABLE'):
            if table_of(st) in SKIP_TABLES:
                continue
            if 'ADD CONSTRAINT' in upper:
                # Skip if a constraint of that name already exists, and still
                # guard against an equivalent constraint created by init-db
                # under a DIFFERENT name (e.g. a primary key), which raises
                # invalid_table_definition rather than duplicate_object.
                m = re.search(r'ADD CONSTRAINT\s+"?([A-Za-z_0-9]+)"?', st)
                tbl = table_of(st)
                body = st.rstrip().rstrip(';').replace("'", "''")
                name = m.group(1) if m else None
                if name and tbl:
                    constraints.append(
                        "DO $c$ BEGIN\n"
                        "    IF NOT EXISTS (SELECT 1 FROM pg_constraint\n"
                        f"                   WHERE conname = '{name}'\n"
                        f"                     AND conrelid = 'public.{tbl}'::regclass) THEN\n"
                        f"        EXECUTE '{body}';\n"
                        "    END IF;\n"
                        "EXCEPTION WHEN duplicate_table OR duplicate_object\n"
                        "               OR invalid_table_definition THEN NULL;\n"
                        "END $c$;"
                    )
            elif 'OWNED BY' in upper or 'SET DEFAULT' in upper:
                constraints.append(st)

    # Column backfill for tables init-db already created.
    backfill = []
    for tbl, col, typ, default, notnull in columns:
        if tbl in SKIP_TABLES:
            continue
        line = f'ALTER TABLE public.{tbl} ADD COLUMN IF NOT EXISTS {col} {typ}'
        if default:
            line += f' DEFAULT {default}'
        # NOT NULL is deliberately omitted unless a default backs it: adding a
        # NOT NULL column to a table that already has rows would fail. Fresh
        # databases still get NOT NULL from the CREATE TABLE above.
        if notnull and default:
            line += ' NOT NULL'
        backfill.append(line + ';')

    def section(title, items):
        if not items:
            return ''
        rule = '-' * 74
        return f'\n-- {rule}\n-- {title} ({len(items)})\n-- {rule}\n' + '\n\n'.join(items) + '\n'

    return (
        HEADER
        + section('Tables', tables)
        + section('Sequences', seqs)
        + section('Column backfill -- converges tables that init-db already made', backfill)
        + section('Functions', funcs)
        + section('Views', views)
        + section('Indexes', indexes)
        + section('Constraints and defaults', constraints)
        + section('Triggers', triggers)
        + FOOTER
    )


def main() -> int:
    dump_path, cols_path, out_path = sys.argv[1], sys.argv[2], sys.argv[3]

    with open(dump_path, encoding='utf-8') as fh:
        statements = split_statements(fh.read())

    columns = []
    with open(cols_path, encoding='utf-8') as fh:
        for raw in fh:
            parts = raw.rstrip('\n').split('\t')
            if len(parts) != 5:
                continue
            tbl, col, typ, default, notnull = parts
            columns.append((tbl, col, typ, default or None, notnull == 'YES'))

    sql = emit(statements, columns)
    with open(out_path, 'w', encoding='utf-8') as fh:
        fh.write(sql)

    print(f'wrote {out_path}: {len(sql)} bytes, '
          f'{len(statements)} source statements, {len(columns)} columns')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
